class SaasCatalogueService {
  private modules: CommercialModule[];
  private addons: CommercialAddon[];
  private overrides: CustomerCommercialOverride[];

  constructor() {
    this.modules = this.loadModules();
    this.addons = this.loadAddons();
    this.overrides = this.loadOverrides();
  }

  private loadModules(): CommercialModule[] {
    try {
      const saved = localStorage.getItem(STORAGE_KEY_CATALOGUE);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length >= 16) {
          return parsed;
        }
      }
    } catch {
      // Fallback
    }
    return INITIAL_COMMERCIAL_MODULES;
  }

  private loadAddons(): CommercialAddon[] {
    try {
      if (typeof localStorage !== 'undefined') {
        const saved = localStorage.getItem(STORAGE_KEY_ADDONS);
        if (saved) {
          const parsed = JSON.parse(saved);
          if (Array.isArray(parsed) && parsed.length >= 15) {
            return parsed;
          }
        }
      }
    } catch {
      // Fallback
    }
    return INITIAL_COMMERCIAL_ADDONS;
  }

  private loadOverrides(): CustomerCommercialOverride[] {
    try {
      if (typeof localStorage !== 'undefined') {
        const saved = localStorage.getItem(STORAGE_KEY_OVERRIDES);
        if (saved) {
          const parsed = JSON.parse(saved);
          if (Array.isArray(parsed)) {
            return parsed.filter(
              (o: any) =>
                o &&
                !String(o.id || '').includes('abc-mfg') &&
                !String(o.tenantName || '').toLowerCase().includes('abc manufacturing') &&
                !String(o.tenantName || '').toLowerCase().includes('abc industries')
            );
          }
        }
      }
    } catch {
      // Fallback
    }
    return [];
  }

  public getModules(): CommercialModule[] {
    return this.modules;
  }

  public getModuleByKey(key: string): CommercialModule | undefined {
    return this.modules.find((m) => m.moduleKey === key);
  }

  public getAllFeatures(): CommercialFeature[] {
    return this.modules.flatMap((m) => m.features);
  }

  public getFeatureByKey(key: string): CommercialFeature | undefined {
    for (const mod of this.modules) {
      const found = mod.features.find((f) => f.featureKey === key);
      if (found) return found;
    }
    return undefined;
  }

  public getAddons(): CommercialAddon[] {
    try {
      if (typeof localStorage !== 'undefined') {
        const saved = localStorage.getItem(STORAGE_KEY_ADDONS);
        if (saved) {
          const parsed = JSON.parse(saved);
          if (Array.isArray(parsed) && parsed.length >= 15) {
            this.addons = parsed;
          }
        }
      }
    } catch {}
    return this.addons;
  }

  public saveAddon(addon: CommercialAddon): void {
    const existingIndex = this.addons.findIndex(
      (a) => a.addonKey === addon.addonKey || a.id === addon.id
    );
    if (existingIndex >= 0) {
      this.addons[existingIndex] = { ...this.addons[existingIndex], ...addon };
    } else {
      this.addons.unshift(addon);
    }
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(STORAGE_KEY_ADDONS, JSON.stringify(this.addons));
      window.dispatchEvent(new CustomEvent('addons:data_updated', { detail: { addon } }));
    }
  }

  public deleteAddon(addonKey: string): void {
    this.addons = this.addons.filter((a) => a.addonKey !== addonKey && a.id !== addonKey);
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(STORAGE_KEY_ADDONS, JSON.stringify(this.addons));
      window.dispatchEvent(new CustomEvent('addons:data_updated', { detail: { addonKey } }));
    }
  }

  public getCustomerOverrides(): CustomerCommercialOverride[] {
    return this.overrides;
  }

  public saveCustomerOverride(override: CustomerCommercialOverride): void {
    const existingIndex = this.overrides.findIndex(
      (o) => o.id === override.id || o.tenantId === override.tenantId
    );
    if (existingIndex >= 0) {
      this.overrides[existingIndex] = override;
    } else {
      this.overrides.push(override);
    }
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(STORAGE_KEY_OVERRIDES, JSON.stringify(this.overrides));
    }
  }

  public deleteCustomerOverride(id: string): void {
    this.overrides = this.overrides.filter((o) => o.id !== id && o.tenantId !== id);
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(STORAGE_KEY_OVERRIDES, JSON.stringify(this.overrides));
    }
  }

  public updateFeatureCommercialStatus(
    featureKey: string,
    commercialType: CommercialFeature['commercialType'],
    minPlan: PlanTierCode
  ): void {
    for (const mod of this.modules) {
      const feat = mod.features.find((f) => f.featureKey === featureKey);
      if (feat) {
        feat.commercialType = commercialType;
        feat.minPlan = minPlan;
        localStorage.setItem(STORAGE_KEY_CATALOGUE, JSON.stringify(this.modules));
        return;
      }
    }
  }

  public updateAddonPrice(addonKey: string, newPrice: number): void {
    const addon = this.addons.find((a) => a.addonKey === addonKey);
    if (addon) {
      addon.monthlyPrice = newPrice;
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(STORAGE_KEY_ADDONS, JSON.stringify(this.addons));
      }
    }
  }
}

export const saasCatalogueService = new SaasCatalogueService();
